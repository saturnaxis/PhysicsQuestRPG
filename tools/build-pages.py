#!/usr/bin/env python3
"""Build the GitHub Pages site and its offline cache manifest."""

import hashlib
import json
import shutil
from tempfile import TemporaryDirectory
from pathlib import Path


def refresh_cache(root):
    worker = root / "sw.js"
    extensions = {".html", ".js", ".css", ".webmanifest", ".webp", ".png", ".svg", ".ico", ".flac"}
    candidates = list(root.iterdir())
    for folder in ("art", "audio", "icons"):
        candidates.extend((root / folder).rglob("*"))
    paths = sorted(
        file.relative_to(root).as_posix()
        for file in candidates
        if file.is_file() and file.suffix in extensions and file != worker
    )

    version = hashlib.sha256()
    for path in paths:
        version.update(path.encode("utf-8") + b"\0")
        with (root / path).open("rb") as stream:
            version.update(hashlib.file_digest(stream, "sha256").digest())

    marker = "// BEGIN GENERATED PRECACHE\n"
    end = "// END GENERATED PRECACHE"
    source = worker.read_text(encoding="utf-8")
    prefix, generated = source.split(marker, 1)
    _, suffix = generated.split(end, 1)
    build = f"const buildVersion = {json.dumps(version.hexdigest()[:20])};\n"
    assets = f"const assets = {json.dumps(paths, indent=2)};\n"
    worker.write_text(prefix + marker + build + assets + end + suffix, encoding="utf-8")
    return len(paths)


def main():
    repo = Path(__file__).resolve().parents[1]
    source = repo / "src"
    docs = repo / "docs"
    marker = ".physicsquest-pages"
    if docs.exists() and not (docs / marker).is_file():
        raise SystemExit("The existing docs/ folder was not generated by this build. Use a clean checkout or move that folder aside first.")

    # Finish and validate the new output before replacing the previous site.
    with TemporaryDirectory(prefix=".pages-build-", dir=repo) as temporary:
        work = Path(temporary)
        staged = work / "site"
        shutil.copytree(source, staged)
        for filename in ("index.html", "manifest.webmanifest", "sw.js"):
            if not (staged / filename).is_file():
                raise SystemExit(f"Missing source file: src/{filename}")
        count = refresh_cache(staged)
        (staged / ".nojekyll").touch()
        (staged / marker).write_text("Generated by tools/build-pages.py. Edit src/ and rebuild.\n", encoding="utf-8")

        previous = work / "previous"
        if docs.exists():
            docs.rename(previous)
        try:
            staged.rename(docs)
        except OSError:
            if previous.exists():
                previous.rename(docs)
            raise

    print(f"Built docs/ with {count} offline files.")


if __name__ == "__main__":
    main()
